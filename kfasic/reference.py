"""Floating-point reference Kalman filter and test scenarios.

The filter is the paper's n=2, r=1, m=1 case (Eq. 3-7):

    x- = Phi x + G u              P- = Phi P Phi^T + Q
    K  = P- H^T (H P- H^T + R)^-1
    x+ = x- + K (y - H x-)        P+ = (I - K H) P-
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from . import fixed


@dataclass
class KfParams:
    x: np.ndarray                      # (2,)   initial state
    P: np.ndarray                      # (2,2)  initial covariance
    Phi: np.ndarray                    # (2,2)  state transition
    Q: np.ndarray                      # (2,2)  process noise covariance
    H: np.ndarray                      # (2,)   measurement row vector
    R: float                           # measurement noise variance
    G: np.ndarray = field(default_factory=lambda: np.zeros(2))  # control input
    u: float = 0.0

    def registers(self) -> dict[str, float]:
        """Values for the named data-bank registers of fw/kf_2d.s."""
        return {
            "x1": self.x[0], "x2": self.x[1],
            "p11": self.P[0, 0], "p12": self.P[0, 1],
            "p21": self.P[1, 0], "p22": self.P[1, 1],
            "phi11": self.Phi[0, 0], "phi12": self.Phi[0, 1],
            "phi21": self.Phi[1, 0], "phi22": self.Phi[1, 1],
            "q11": self.Q[0, 0], "q12": self.Q[0, 1],
            "q21": self.Q[1, 0], "q22": self.Q[1, 1],
            "h1": self.H[0], "h2": self.H[1], "r11": self.R,
            "g1": self.G[0], "g2": self.G[1], "u": self.u,
        }


def kf_step(x, P, p: KfParams, y: float):
    x_pred = p.Phi @ x + p.G * p.u
    P_pred = p.Phi @ P @ p.Phi.T + p.Q
    S = p.H @ P_pred @ p.H + p.R
    K = P_pred @ p.H / S
    x_new = x_pred + K * (y - p.H @ x_pred)
    P_new = (np.eye(2) - np.outer(K, p.H)) @ P_pred
    return x_new, P_new


def run_float(p: KfParams, ys) -> np.ndarray:
    """Return the (N, 2) array of state estimates after each measurement."""
    x, P = p.x.astype(float), p.P.astype(float)
    out = []
    for y in ys:
        x, P = kf_step(x, P, p, float(y))
        out.append(x.copy())
    return np.array(out)


