def tracking_params() -> KfParams:
    """Constant-velocity tracking setup used by the original project."""
    return KfParams(
        x=np.array([0.0, 0.03]),
        P=np.eye(2),
        Phi=np.array([[1.0, 0.1], [0.0, 1.0]]),
        Q=0.01 * np.eye(2),
        H=np.array([1.0, 0.0]),
        R=0.1,
    )


def tracking_data(n: int, seed: int = 42):
    """Ground truth and noisy measurements, as generated by the original
    project's kf_gen_test.py (same RNG call order, values rounded to the
    6 decimals that its text files carried).  Note the sequence depends on n:
    all truth samples are drawn before the measurement noise.
    """
    rng = np.random.RandomState(seed)
    dt, pos, vel = 0.1, 0.0, 0.03
    truth = []
    for _ in range(n):
        truth.append(pos)
        pos += vel * dt + rng.normal(0, 0.1)
        vel += rng.normal(0, 0.1 * 0.1)
    meas = [t + rng.normal(0, 0.3) for t in truth]
    r6 = lambda v: float(f"{v:.6f}")  # noqa: E731
    return np.array([r6(t) for t in truth]), np.array([r6(m) for m in meas])


def random_params(rng: np.random.Generator) -> KfParams:
    """A random, stable (spectral radius < 0.99) 2-state system whose states
    stay far inside the +/-512 range of Q9.14."""
    while True:
        dt = rng.uniform(0.01, 0.5)
        Phi = np.array([[rng.uniform(0.9, 1.0), dt],
                        [rng.uniform(-0.05, 0.05), rng.uniform(0.85, 1.0)]])
        if np.abs(np.linalg.eigvals(Phi)).max() < 0.99:
            break
    qd = rng.uniform(0.001, 0.05, size=2)
    qo = rng.uniform(-0.3, 0.3) * np.sqrt(qd[0] * qd[1])
    Q = np.array([[qd[0], qo], [qo, qd[1]]])
    H = np.array([rng.uniform(0.5, 2.0), rng.uniform(-0.5, 0.5)])
    return KfParams(
        x=rng.uniform(-5, 5, size=2),
        P=np.diag(rng.uniform(0.1, 3.0, size=2)),
        Phi=Phi, Q=Q, H=H,
        R=rng.uniform(0.05, 2.0),
        G=rng.uniform(-0.5, 0.5, size=2),
        u=rng.uniform(-1.0, 1.0),
    )


def simulate(p: KfParams, n: int, rng: np.random.Generator) -> np.ndarray:
    """Noisy measurements of the true system p (process + measurement noise)."""
    x = p.x.copy()
    L = np.linalg.cholesky(p.Q + 1e-12 * np.eye(2))
    ys = []
    for _ in range(n):
        x = p.Phi @ x + p.G * p.u + L @ rng.standard_normal(2)
        ys.append(p.H @ x + np.sqrt(p.R) * rng.standard_normal())
    return np.clip(np.array(ys), -500, 500)


def quantize(p: KfParams) -> dict[str, int]:
    """Register name -> Q9.14 word."""
    return {k: fixed.from_float(v) for k, v in p.registers().items()}
